#!/usr/bin/env python3
"""Testbench generator + checker for the OpenRAM SKY130 16x8 macro.

usage (run from ~/sram_work/sim):
  python3 sramtb.py gen   <test> [--netlist sch|pex] [--corner tt|ff|ss|fs|sf] [--temp C]
                          [--period NS] [--sample NS] [--tstep NS] [--glitch] [--dump] [--name RUN]
  python3 sramtb.py check <run>
  python3 sramtb.py wave  <run>        # waveform table (needs --dump, or the debug test on sch)

  then simulate with:  ~/sram_work/nixrun ngspice -b runs/<run>.sp -o runs/<run>.log
  (or just use ./run.sh, which does gen + sim + check)

tests:
  march  - write all 16 addresses, read all back, then again with inverted data (256 bit checks)
  debug  - 6 cycles (w0, w1, r0, r1) with internal waveforms dumped to runs/<run>.dat
  wtoggle - write-ability: flip all bits of addr 0 and 5 repeatedly, read back after each write

netlists:
  sch    - OpenRAM schematic netlist (no wire parasitics)  -> netlist/sram_tb.sp
  pex    - netlist extracted from the GDS with parasitic C  -> netlist/sram_pex.spice

--sample : when dout is sampled, in ns after the clock edge that ENDS the read
           cycle (default 0.05 = OpenRAM's own functional-test convention).
Run name defaults to <test>_<netlist>. Files: runs/<run>.{sp,json,log[,dat]}.
"""
import json, re, argparse, os

PDK_LIB = ".lib \"" + os.path.join(os.environ.get("PDK_ROOT", os.path.expanduser("~/OpenRAM")), "sky130A/libs.tech/ngspice/sky130.lib.spice") + "\" {corner}"
CELL = "sky130_sram_0kbytes_1rw_8x16_8"
NWORDS, NBITS, NADDR = 16, 8, 5
VDD = 1.8
NETLISTS = {  # name -> (file, port order of the top subckt in that file)
    "sch": ("netlist/sram_tb.sp",
            [f"din0_{b}" for b in range(9)] + [f"a0_{b}" for b in range(5)] +
            ["CSB0", "WEB0", "clk0", "SPARE_WEN0_0"] + [f"dout0_{b}" for b in range(9)] + ["vdd", "gnd"]),
    "pex": ("netlist/sram_pex.spice",
            ["CSB0", "WEB0", "clk0"] + [f"din0_{b}" for b in range(9)] + [f"dout0_{b}" for b in range(9)] +
            [f"a0_{b}" for b in range(5)] + ["SPARE_WEN0_0", "vdd", "gnd"]),
}
CELLQ = "xsram.xbank0.xbitcell_array.xreplica_bitcell_array.xbitcell_array.xbit_r{}_c0.q"
DEBUG_SIGS = ["clk0", "xsram.clk_buf0", "xsram.wl_en0", "xsram.s_en0", "xsram.w_en0",
              "xsram.p_en_bar0", "xsram.a0_0", "xsram.xbank0.wl_0_0", "xsram.xbank0.wl_0_1",
              "xsram.xbank0.bl_0_0", "xsram.xbank0.br_0_0", "dout0_0", CELLQ.format(0), CELLQ.format(1)]
# PEX: clean probe nodes added by prep_netlist.sh into netlist/sram_pex_probe.spice
DEBUG_SIGS_PEX = ["clk0", "xsram.wlenp", "xsram.wenp", "xsram.senp", "xsram.penp", "xsram.rblp",
                  "xsram.wlp0", "xsram.wlp5", "xsram.blp", "xsram.brp", "dout0_0"]


def ops_march():
    pat = [((a << 4) | (15 - a)) & 0xFF for a in range(NWORDS)]
    ops = [["idle", 0, 0]]
    for data in (pat, [~d & 0xFF for d in pat]):
        ops += [["w", a, data[a]] for a in range(NWORDS)]
        ops += [["r", a, data[a]] for a in range(NWORDS)]
    return ops


def ops_debug():
    return [["idle", 0, 0], ["w", 0, 0x0F], ["w", 1, 0xF0], ["r", 0, 0x0F], ["r", 1, 0xF0], ["idle", 0, 0]]


def ops_wtoggle():
    # write-ability: flip every bit of addr 0 and addr 5 several times, reading back after each write
    ops = [["idle", 0, 0]]
    for d in (0x00, 0xFF, 0x00, 0x55, 0xAA, 0x0F, 0xF0):
        for a in (0, 5):
            ops += [["w", a, d], ["r", a, d]]
    return ops


TESTS = {"march": ops_march, "debug": ops_debug, "wtoggle": ops_wtoggle}


def pwl(vals, P):
    pts = [f"0n {vals[0]*VDD:.1f}v"]
    for c in range(1, len(vals)):
        pts.append(f"{c*P-0.505:.3f}n {vals[c-1]*VDD:.1f}v {c*P-0.495:.3f}n {vals[c]*VDD:.1f}v")
    return "PWL (" + " ".join(pts) + ")"


def gen(test, netlist, P, sample, run, glitch=False, corner="tt", temp=25.0, dump=False, tstep=None):
    ops = TESTS[test]()
    nc = len(ops)
    nfile, ports = NETLISTS[netlist]
    dump = dump or (test == "debug" and netlist == "sch")
    sigs = DEBUG_SIGS if netlist == "sch" else DEBUG_SIGS_PEX
    if (glitch or dump) and netlist == "pex":
        nfile = nfile.replace(".spice", "_probe.spice")
    L = [f"* {test} test, {netlist} netlist, {corner} {temp}C, period {P} ns, generated by sramtb.py",
         PDK_LIB.format(corner=corner), f".temp {temp}",
         f'.include "{nfile}"', f"Vvdd vdd 0 {VDD}", "Xsram " + " ".join(ports + [CELL])]
    L += [f"CD{b} dout0_{b} 0 27.56f" for b in range(NBITS + 1)]
    for b in range(NBITS + 1):
        L.append(f"Vdin0_{b} din0_{b} 0 " + pwl([(o[2] >> b) & 1 if o[0] == "w" and b < NBITS else 0 for o in ops], P))
    for b in range(NADDR):
        L.append(f"Va0_{b} a0_{b} 0 " + pwl([(o[1] >> b) & 1 if o[0] != "idle" else 0 for o in ops], P))
    L.append("VCSB0 CSB0 0 " + pwl([1 if o[0] == "idle" else 0 for o in ops], P))
    L.append("VWEB0 WEB0 0 " + pwl([0 if o[0] == "w" else 1 for o in ops], P))
    L.append("VSPARE_WEN0_0 SPARE_WEN0_0 0 0")
    # rising clock edges at k*P - 0.005 ns (k >= 1); cycle c's inputs are captured at edge ~c*P
    L.append(f"Vclk0 clk0 0 PULSE (0 {VDD} {P-0.005}n 0.01n 0.01n {P/2-0.01}n {P}n)")
    for c, o in enumerate(ops):
        if o[0] == "r":
            for b in range(NBITS):
                L.append(f".meas tran m{c}b{b}e FIND v(dout0_{b}) AT={(c+1)*P+sample:.3f}n")
    if glitch:  # peak of every wordline in the 3 ns after each rising edge
        wl = "xsram.xbank0.wl_0_{}" if netlist == "sch" else "xsram.wlp{}"
        for c in range(1, nc):
            for r in range(NWORDS + 1):
                L.append(f".meas tran g{c}r{r}e MAX v({wl.format(r)}) FROM={c*P-0.005:.3f}n TO={c*P+3:.3f}n")
    if tstep is None:
        # 0.1 ns: with 1 ns, ngspice stepped over fast write events at the sf corner -> false failures
        tstep = 0.1
    L.append(f".tran {tstep}n {nc*P+P/2:.0f}n")   # NOTE: in ngspice the tstep also caps the max time step
    if dump:
        L += [".control", "run", f"wrdata runs/{run}.dat " + " ".join(f"v({s})" for s in sigs), ".endc"]
    L.append(".end")
    open(f"runs/{run}.sp", "w").write("\n".join(L) + "\n")
    json.dump({"test": test, "netlist": netlist, "corner": corner, "temp": temp, "period": P,
               "sample": sample, "tstep": tstep, "ops": ops, "glitch": glitch, "sigs": sigs if dump else []},
              open(f"runs/{run}.json", "w"))
    print(f"runs/{run}.sp: {test} on {netlist} @ {corner} {temp}C, {nc} cycles, period {P} ns, "
          f"sample at edge+{sample} ns, tstep {tstep} ns, {sum(o[0]=='r' for o in ops)*NBITS} bit checks")


def check(run):
    cfg = json.load(open(f"runs/{run}.json"))
    v = {(int(m[1]), int(m[2])): float(m[3]) for m in
         re.finditer(r"^m(\d+)b(\d+)e\S*\s*=\s*([-+\d.eE]+)", open(f"runs/{run}.log").read(), re.M)}
    nbad = nmeas = 0
    for c, o in enumerate(cfg["ops"]):
        if o[0] != "r":
            continue
        got = 0
        for b in range(NBITS):
            if (c, b) in v:
                nmeas += 1
                got |= (v[(c, b)] > VDD / 2) << b
        diff = bin(got ^ o[2]).count("1")
        nbad += diff
        print(f"{'OK ' if not diff else 'BAD'} cycle {c:2d} addr {o[1]:2d} expected {o[2]:08b} got {got:08b}")
    total = sum(o[0] == 'r' for o in cfg['ops']) * NBITS
    print(f"\n[{run}] measured {nmeas}/{total}, bit failures {nbad} -> {'PASS' if nmeas == total and not nbad else 'FAIL'}")
    if cfg.get("glitch"):
        g = {(int(m[1]), int(m[2])): float(m[3]) for m in
             re.finditer(r"^g(\d+)r(\d+)e\S*\s*=\s*([-+\d.eE]+)", open(f"runs/{run}.log").read(), re.M)}
        worst = (0.0, None, None)
        for c in range(2, len(cfg["ops"])):   # skip edge 1: flop states are undefined before it
            prev = cfg["ops"][c-1]
            legit = prev[1] if prev[0] != "idle" else None   # previous row may still be on just after the edge
            for r in range(NWORDS + 1):
                if r != legit and g.get((c, r), 0) > worst[0]:
                    worst = (g[(c, r)], c, r)
        print(f"[{run}] worst wordline glitch after a clock edge: {worst[0]:.2f} V "
              f"(row {worst[2]}, edge starting cycle {worst[1]}); {len(g)} wordline checks")


def wave(run):
    cfg = json.load(open(f"runs/{run}.json"))
    rows = [list(map(float, l.split())) for l in open(f"runs/{run}.dat") if l.strip()]
    sigs = cfg.get("sigs") or DEBUG_SIGS
    sig = {s: [r[2*i+1] for r in rows] for i, s in enumerate(sigs)}
    names = [s.split('.')[-1] if not s.endswith(".q") else s.split('.')[-2][5:] + ".q" for s in sigs]
    print("time(ns) " + " ".join(f"{n[:9]:>9}" for n in names))
    step, k, tt = cfg["period"] / 8, 0, 0.0
    while tt <= rows[-1][0] * 1e9:
        while k < len(rows) - 1 and rows[k][0] * 1e9 < tt:
            k += 1
        print(f"{tt:8.1f} " + " ".join(f"{sig[s][k]:9.2f}" for s in sigs))
        tt += step


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["gen", "check", "wave"])
    ap.add_argument("what", help="test name for gen, run name for check/wave")
    ap.add_argument("--netlist", choices=list(NETLISTS), default="sch")
    ap.add_argument("--period", type=float, default=40.0)
    ap.add_argument("--sample", type=float, default=0.05)
    ap.add_argument("--name", help="run name (default <test>_<netlist>)")
    ap.add_argument("--corner", default="tt", choices=["tt", "ff", "ss", "fs", "sf"])
    ap.add_argument("--temp", type=float, default=25.0)
    ap.add_argument("--glitch", action="store_true",
                    help="also measure every wordline's peak in the 3 ns after each clock edge")
    ap.add_argument("--tstep", type=float, help="ngspice .tran step / max step in ns (default 0.1; 1 is faster but gave false failures at sf)")
    ap.add_argument("--dump", action="store_true", help="dump internal waveforms to runs/<run>.dat (any test)")
    a = ap.parse_args()
    if a.cmd == "gen":
        sfx = ("" if a.corner == "tt" and a.temp == 25 else f"_{a.corner}{a.temp:g}C") + ("_glitch" if a.glitch else "")
        gen(a.what, a.netlist, a.period, a.sample, a.name or f"{a.what}_{a.netlist}{sfx}", a.glitch, a.corner, a.temp, a.dump, a.tstep)
    elif a.cmd == "check":
        check(a.what)
    else:
        wave(a.what)
